import assert from 'node:assert/strict';
import fs from 'node:fs';
import { readTcmObservations, writeTcmObservations } from '../tcm-observation-model.js';
import { aggregateInterventionResponses } from '../analysis/intervention-response-aggregator.js';
import { analyzeTcmClusters } from '../analysis/tcm-cluster-engine.js';
import { adaptRecommendationContext } from '../analysis/recommendation-context-adapter.js';

const empty = readTcmObservations([]);
assert.equal(empty.cold_sensation, null, '未记录必须保持 null');
const tags = writeTcmObservations(['普通标签'], { cold_sensation: 'no', nausea: 'yes', diarrhea: 'no', warmth_relief: 'no', bloating: 'yes', poor_appetite: 'no', body_heaviness: 'no' });
const restored = readTcmObservations(tags);
assert.equal(restored.cold_sensation, 'no', '明确否不能变成未记录');
assert.equal(restored.nausea, 'yes');
assert.equal(restored.diarrhea, 'no');
assert.equal(restored.warmth_relief, 'no');
assert.equal(restored.bloating, 'yes');
assert.equal(restored.poor_appetite, 'no');
const adapted = adaptRecommendationContext({ today_record: { symptomTags: tags, fieldStatus: {} }, record_date: '2026-08-13' });
assert.equal(adapted.context.nausea, true, '恶心必须进入干预匹配上下文');
assert.equal(adapted.context.diarrhea, false, '明确无腹泻必须区别于未记录');
assert.ok(adapted.current_discomforts.some((item) => item.metric === 'nausea'), '恶心必须能触发当前不适门控');

const feedback = Array.from({ length: 3 }, (_, index) => ({ intervention_id: 'tea_1', intervention_name: '测试茶饮', target: 'sleep_quality', used_at: `2026-08-0${index + 1}T12:00:00Z`, helpful: index !== 2, before: 4, after: 2 }));
const response = aggregateInterventionResponses(feedback);
assert.equal(response.length, 1);
assert.equal(response[0].interventionName, '测试茶饮');
assert.equal(response[0].dataLabel, '数据仍少');
assert.equal(aggregateInterventionResponses(feedback.slice(0, 2)).length, 0, '少于3次不得形成汇总');

const tcmRules = JSON.parse(fs.readFileSync(new URL('../knowledge/tcm_cluster_rules.json', import.meta.url), 'utf8'));
const noTcm = analyzeTcmClusters({ logs: {}, periods: [], as_of: '2026-08-13', rules_config: tcmRules });
assert.equal(noTcm.filter((item) => item.status === 'active').length, 0, '无新增体感记录时不得形成可展示的 TCM Cluster');
assert.ok(noTcm.every((item) => item.status === 'insufficient'), '数据不足状态必须保留，供质量审计使用');

const html = fs.readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const app = fs.readFileSync(new URL('../app.js', import.meta.url), 'utf8');
const traditional = fs.readFileSync(new URL('../traditional-care.js', import.meta.url), 'utf8');
const wellness = fs.readFileSync(new URL('../wellness-engine.js', import.meta.url), 'utf8');
const serviceWorker = fs.readFileSync(new URL('../sw.js', import.meta.url), 'utf8');
for (const name of ['coldSensation', 'warmthRelief', 'nausea', 'diarrhea', 'bloating', 'poorAppetite', 'bodyHeaviness']) assert.match(html, new RegExp(`name="${name}"`));
assert.doesNotMatch(html, /name="bloatingLevel"|name="appetiteLevel"/);
assert.doesNotMatch(html, /name="coldHandsFeet"/);
assert.match(app, /showToast\('已保存 ✓'\)/);
assert.match(app, /requestIdleCallback/);
assert.match(app, /renderCurrentView\(\{heavy:false\}\)/);
assert.match(traditional, /runAnalysis\(/, '首页针对性调养必须走统一分析调度器');
assert.doesNotMatch(traditional, /buildRecommendationEvidence\(/, '首页不得保留独立的重复分析入口');
assert.equal(tcmRules.minimum_cycles, 2);
assert.doesNotMatch(html, /traditional-care\.js|personal-insights\.js|insights-page\.js/, '大型功能模块不得阻塞首屏');
assert.match(html, /app\.js\?v=94/);
assert.match(app, /import\('\.\/insights-page\.js'\)/, '趋势页必须按需加载');
assert.match(app, /import\('\.\/traditional-care\.js'\)/, '传统调养必须按需加载');
assert.match(serviceWorker, /period-helper-v94/);
assert.match(html, /Content-Security-Policy/);
assert.match(html, /connect-src 'self' https:\/\/period-sync\.rsr-ren\.workers\.dev/);
assert.match(app, /else if\(id==='calendar'\)\{renderCalendarEnhanced\(model,phase\);renderCalendarStatusAsync\(state\.logs,currentNavigation,currentRender\);renderWellnessEnhancements\(context,'calendar'\)/, '日历每次重绘后都必须恢复身体状态图标并携带当前 render token');
assert.doesNotMatch(app, /calendarCursor\.setMonth\([^;]+\);renderCalendar\(\)/, '月份切换不得回退到不会恢复状态图标的旧日历渲染器');
for (const control of ['monthViewBtn', 'yearViewBtn', 'calendarYearSelect', 'calendarTodayBtn']) assert.match(app, new RegExp(`#${control.replace(/[.*+?^${}()|[\\]\\]/g, '\\$&')}[^\\n]+renderView\\('calendar',\\{heavy:false\\}\\)`), `${control} 重绘后必须恢复身体状态图标`);
assert.match(wellness, /export function renderWellnessEnhancements\(context, view = 'today'\)/, '页面增强器必须通过显式模块接口调用');
assert.match(wellness, /if \(view === 'calendar'\) \{ renderCycleObservation/, '日历页只补充日历所需内容');
assert.doesNotMatch(serviceWorker, /analysis\/analysis-orchestrator\.js|analysis\/explanation-object\.js|knowledge\/|og\.png|icon-512/, '非首屏资源不得进入首次预缓存');
console.log('Insights v1 与 TCM 体感模型检查通过');
